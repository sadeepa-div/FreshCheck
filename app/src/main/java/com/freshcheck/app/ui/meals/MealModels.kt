data class RecipeIngredient(val key: String, val name: String, val quantity: Double, val unit: String)
data class RecipeUi(val id: String, val name: String, val category: String, val minutes: Int,
    val servings: Int, val ingredients: List<RecipeIngredient>, val steps: List<String>, val preferences: Set<String>)
data class IngredientMatch(val ingredient: RecipeIngredient, val available: Boolean, val needsReplacementOrCheck: Boolean)
fun ingredientKey(name: String): String = when (val key = name.trim().lowercase(Locale.ROOT)) {
    "avocados" -> "avocado"; "apples" -> "apple"; "tomatoes" -> "tomato"; "carrots" -> "carrot"; else -> key
}
fun eligibleIngredient(item: FoodItemUi) = item.quantity.isFinite() && item.quantity > 0 &&
    (item.condition == FreshnessCondition.Fresh || item.condition == FreshnessCondition.UseSoon)
fun matchIngredients(recipe: RecipeUi, food: List<FoodItemUi>): List<IngredientMatch> =
    recipe.ingredients.map { ingredient ->
        val candidates = food.filter { ingredientKey(it.name) == ingredient.key }
        IngredientMatch(ingredient, candidates.any(::eligibleIngredient),
            candidates.isNotEmpty() && candidates.none(::eligibleIngredient))
    }
fun rescueItems(food: List<FoodItemUi>, today: LocalDate) = food.filter {
    eligibleIngredient(it) && (it.condition == FreshnessCondition.UseSoon || (it.recheck != null && it.recheck <= today))
}.sortedWith(compareBy<FoodItemUi> { it.recheck ?: LocalDate.MAX }.thenBy { it.id })
/** Replaceable deterministic UI rule: ingredient-name presence only, not AI, safety or quantity validation.
 * Rescue recipes require a match to an eligible item requiring attention.
 */
fun recommendRecipes(recipes: List<RecipeUi>, food: List<FoodItemUi>, rescueOnly: Boolean, today: LocalDate): List<RecipeUi> {
    val priority = rescueItems(food, today).map { ingredientKey(it.name) }.toSet()
    return recipes.filter { !rescueOnly || it.ingredients.any { ingredient -> ingredient.key in priority } }
        .sortedWith(compareByDescending<RecipeUi> { recipe ->
            matchIngredients(recipe, food).count { it.available }
        }.thenBy { it.id })
}
fun scaledIngredient(ingredient: RecipeIngredient, recipe: RecipeUi, servings: Int): Double {
    require(servings in 1..8 && recipe.servings > 0)
    return ingredient.quantity * servings / recipe.servings
}
